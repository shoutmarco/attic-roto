def small_rows(ch):
    rows = S[ch]
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
    return [sum(0x80 >> i for i, c in enumerate(r) if c == "#") for r in rows]


def big_rows(font, ch):
    im = Image.new("1", (8, 16), 0)
    ImageDraw.Draw(im).text((0, 0), ch, font=font, fill=1)
    return [sum(0x80 >> x for x in range(8) if im.getpixel((x, y))) for y in range(16)]


def main():
    font = ImageFont.truetype(UNIFONT, 16)
    big = [big_rows(font, c) for c in CHARS]
    # trim rows that are blank in every glyph (keeps the cell tight)
    used = [y for y in range(16) if any(g[y] for g in big)]
    y0, y1 = used[0], used[-1] + 1
    out = ["/* SPDX-License-Identifier: GPL-3.0-only",
           " * Generated by tools/gen_roto_font.py — do not edit.",
           " * SMALL: 5x7 drawn for attic-roto. BIG: glyphs from GNU Unifont",
           " * (GPL-2.0+ with font embedding exception / OFL-1.1). */",
           "#ifndef ROTO_FONT_H", "#define ROTO_FONT_H", "",
           f'static const char ROTO_FONT_CHARS[] = "{CHARS}";',
           "#define ROTO_SMALL_W 5", "#define ROTO_SMALL_H 7",
           "#define ROTO_BIG_W 8", f"#define ROTO_BIG_H {y1 - y0}", "",
           f"static const unsigned char ROTO_SMALL[{len(CHARS)}][7] = {{"]
    for c in CHARS:
        out.append("    {" + ",".join(f"0x{b:02X}" for b in small_rows(c)) + f"}}, /* {c!r} */")
    out += ["};", "", f"static const unsigned char ROTO_BIG[{len(CHARS)}][{y1 - y0}] = {{"]
    for c, g in zip(CHARS, big):
        out.append("    {" + ",".join(f"0x{b:02X}" for b in g[y0:y1]) + f"}}, /* {c!r} */")
    # quarter-wave sine, 1024 units per circle, Q14 (16384 = 1.0)
    import math
    sin_q = [round(16384 * math.sin(i * math.pi / 512)) for i in range(257)]
    out += ["};", "", "/* sin, quarter wave: ROTO_SIN[i] = 16384*sin(i*2pi/1024), i = 0..256 */",
            "static const unsigned short ROTO_SIN[257] = {"]
    for i in range(0, 257, 16):
        out.append("    " + ",".join(str(v) for v in sin_q[i:i + 16]) + ",")
    out += ["};", "", "#endif", ""]
    OUT.write_text("\n".join(out))
    print(f"{OUT}: {len(CHARS)} glyphs, big rows {y0}..{y1}")


if __name__ == "__main__":
    main()
