"""Generate firmware/src/roto_font.h: the two bitmap fonts the attic-roto
screens draw with (our own drawing code, lcd_fill only).

  SMALL  5x7, 1 px strokes, hand-drawn here (labels, note names, BPM)
  BIG    8x16 cells from GNU Unifont (header title, centre number at x2)

Each glyph row is one byte, bit 7 = leftmost pixel.
Run:  python3 tools/gen_roto_font.py
"""
